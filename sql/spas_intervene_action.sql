-- Phase A: intervene action pack + close reason + overdue daily job
-- Apply: psql -U postgres -d spas-sql -f sql/spas_intervene_action.sql

create table if not exists spas_intervene_action (
  action_id int8 generated by default as identity not null,
  intervene_id int8 not null,
  action_type varchar(32) not null,
  ref_id int8,
  status char(1) default '0',
  due_at timestamp,
  title varchar(128),
  progress_json text,
  create_by varchar(64) default '',
  create_time timestamp,
  update_by varchar(64) default '',
  update_time timestamp,
  remark varchar(500),
  primary key (action_id)
);
create index if not exists idx_spas_intervene_action_task on spas_intervene_action(intervene_id);
create index if not exists idx_spas_intervene_action_type on spas_intervene_action(action_type, status);
comment on table spas_intervene_action is 'intervention required actions: practice/select/coach/custom';
comment on column spas_intervene_action.action_type is 'practice=布置练习 select=选题补弱 coach=辅导计划 custom=其它';
comment on column spas_intervene_action.status is '0=pending 1=done 2=skipped';

alter table spas_intervene_task add column if not exists close_reason varchar(500);
comment on column spas_intervene_task.close_reason is 'manual close reason when process gate not met';

insert into sys_dict_type(dict_name, dict_type, status, create_by, create_time, remark)
select '干预动作类型', 'spas_intervene_action', '0', 'admin', now(), null
where not exists (select 1 from sys_dict_type where dict_type='spas_intervene_action');

insert into sys_dict_data(dict_sort, dict_label, dict_value, dict_type, css_class, list_class, is_default, status, create_by, create_time)
select * from (values
 (1, '布置练习', 'practice', 'spas_intervene_action', '', 'primary', 'N', '0', 'admin', now()),
 (2, '选题补弱', 'select', 'spas_intervene_action', '', 'success', 'N', '0', 'admin', now()),
 (3, '辅导计划', 'coach', 'spas_intervene_action', '', 'warning', 'Y', '0', 'admin', now()),
 (4, '其它', 'custom', 'spas_intervene_action', '', 'info', 'N', '0', 'admin', now())
) as v(dict_sort, dict_label, dict_value, dict_type, css_class, list_class, is_default, status, create_by, create_time)
where not exists (select 1 from sys_dict_data d where d.dict_type='spas_intervene_action' and d.dict_value=v.dict_value);

-- Daily 01:10 mark overdue open tasks
insert into sys_job(job_id, job_name, job_group, invoke_target, cron_expression, misfire_policy, concurrent, status, create_by, create_time, remark)
select 103, 'SPAS Intervene Overdue', 'DEFAULT', 'spasInterveneTask.markOverdue()', '0 10 1 * * ?', '3', '1', '0', 'admin', now(), 'Mark open intervene tasks past due_date as overdue'
where not exists (select 1 from sys_job where job_id = 103);

update sys_job
   set status = '0',
       invoke_target = 'spasInterveneTask.markOverdue()',
       cron_expression = '0 10 1 * * ?',
       remark = 'Mark open intervene tasks past due_date as overdue'
 where job_id = 103;
